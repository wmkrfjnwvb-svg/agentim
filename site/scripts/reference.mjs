const FENCE = { ts: 'ts', tsx: 'tsx', python: 'python', go: 'go', swift: 'swift', kotlin: 'kotlin', csharp: 'csharp', dart: 'dart' };

/** One page per SDK: every public type and member with its signature and doc comment. */
export function sdkPages() {
  const all = {};
  for (const sdk of SDKS) {
    const list = members(sdk);
    all[sdk.id] = list;
    const lang = FENCE[sdk.lang];
    let t = fm(`${sdk.title} API`, `Every public type, function and member of the ${sdk.title} SDK.`, 100);
    t += `Generated from the source and its doc comments (${sdk.files.map((f) => `[\`sdk/${f}\`](https://github.com/wmkrfjnwvb-svg/agentim/blob/main/sdk/${f})`).join(', ')}).\n\n`;
    t += `\`\`\`${/^(npm|pip|dotnet|dart|go) /.test(INSTALL[sdk.id]) ? 'sh' : lang}\n${INSTALL[sdk.id]}\n\`\`\`\n\n`;
    const top = list.filter((m) => !m.owner);
    const fns = top.filter((m) => m.kind === 'function');
    if (fns.length) {
      t += '## Functions\n\n';
      for (const f of fns) t += `### \`${f.name}\`\n\n\`\`\`${lang}\n${f.signature}\n\`\`\`\n\n${f.doc}\n\n`;
    }
    for (const ty of top.filter((m) => m.kind !== 'function')) {
      t += `## \`${ty.name}\`\n\n\`\`\`${lang}\n${ty.signature}\n\`\`\`\n\n${ty.doc}\n\n`;
      for (const m of list.filter((x) => x.owner === ty.name && x.doc)) t += `### \`${ty.name}.${m.name}\`\n\n\`\`\`${lang}\n${m.signature}\n\`\`\`\n\n${m.doc}\n\n`;
    }
    write(`${sdk.group}/${sdk.id}-api.md`, t);
  }
  return all;
}

export function writeAll() {
  rmSync(join(out, 'reference/open-api'), { recursive: true, force: true });
  const api = openApi();

  const ops = clientOps();
  let t = fm('Client protocol', 'Every request of the WebSocket protocol: what it does and its fields.', 20);
  t += 'Clients send JSON frames `{"op": …, "rid": …, …fields}` over `/ws` and get `{"type": "res", "rid", "ok", …}` back; pushes are described in [Events](/docs/reference/events/). The client SDKs send these for you. Errors use the [error codes](/docs/reference/errors/).\n\nAny request may carry `"trace": "00-<trace id>-<parent id>-<flags>"` ([W3C traceparent](https://www.w3.org/TR/trace-context/)). Agents\' traces are continued; a person\'s app gets a new server trace that links to theirs ([Tracing](/docs/operations/tracing/)).\n\n';
  for (const op of ops) {
    t += `## \`${op.name}\`\n\n${op.doc || ''}\n\n`;
    if (op.fields.length) {
      t += '| Field | Type | Required | Description |\n|---|---|---|---|\n';
      for (const f of op.fields) t += `| \`${f.name}\` | ${esc(f.type)} | ${f.optional ? '' : 'yes'} | ${esc(f.doc)} |\n`;
      t += '\n';
    } else t += 'No fields.\n\n';
  }
  write('reference/client-protocol.md', t);

  const tools = JSON.parse(readFileSync(join(core, 'mcp-tools.json'), 'utf8'));
  t = fm('MCP tools', 'Every tool of the MCP server at POST /mcp.', 30);
  t += 'Agents connect any MCP client to `POST /mcp` with their key (`Authorization: Bearer <agent key>`). These are the tools, in the order `tools/list` returns them.\n\n';
  for (const tool of tools) {
    t += `## \`${tool.name}\`\n\n${tool.title ? `**${tool.title}.** ` : ''}${tool.description}\n\n`;
    const p = tool.inputSchema?.properties ?? {};
    const req = new Set(tool.inputSchema?.required ?? []);
    if (Object.keys(p).length) {
      t += '| Argument | Type | Required | Description |\n|---|---|---|---|\n';
      for (const [k, v] of Object.entries(p)) t += `| \`${k}\` | ${esc(v.type ?? (v.enum ? 'enum' : 'any'))} | ${req.has(k) ? 'yes' : ''} | ${esc(v.description)}${v.enum ? ` One of ${v.enum.map((e) => `\`${e}\``).join(', ')}.` : ''} |\n`;
      t += '\n';
    } else t += 'No arguments.\n\n';
    if (tool.annotations?.readOnlyHint) t += 'Read-only.\n\n';
  }
  write('reference/mcp-tools.md', t);

  const sections = configSections();
  t = fm('Configuration file', 'Every option of agentim.toml, with its default.', 10);
  t += 'Start the server with `agentim --config agentim.toml`. Every section is optional except `[storage]`; unknown keys are refused at start. An annotated example: [`server/agentim.example.toml`](https://github.com/wmkrfjnwvb-svg/agentim/blob/main/server/agentim.example.toml).\n\n';
  for (const s of sections) {
    t += `## \`${s.array ? `[[${s.path}]]` : `[${s.path}]`}\`\n\n${s.doc.replace(/^`\[[^\]]*\]+`:?\s*/, '')}\n\n| Key | Type | Default | Description |\n|---|---|---|---|\n`;
    for (const f of s.fields) t += `| \`${f.name}\` | ${esc(rustType(f.type).type)} | ${f.default ? `\`${esc(f.default)}\`` : ''} | ${esc(f.doc)} |\n`;
    t += '\n';
  }
  write('operations/configuration.md', t);
  const sdks = sdkPages();
  return { sdks, api, ops: ops.map((o) => o.name), tools: tools.map((x) => x.name), config: sections.flatMap((s) => s.fields.map((f) => `${s.path}.${f.name}`)) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = writeAll();
  console.log(`reference: ${Object.keys(r.sdks).length} SDKs, ${r.api.length} endpoints, ${r.ops.length} client ops, ${r.tools.length} MCP tools, ${r.config.length} config keys`);
}
