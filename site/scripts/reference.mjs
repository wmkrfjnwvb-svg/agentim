// Generates the reference pages from the sources (docs/12 §5), so they
// cannot drift from the code: the open API from openapi.json, the client
// protocol from the ClientMsg enum (model.rs), the MCP tools from
// mcp-tools.json (kept equal to the server by tests/mcp.rs) and the
// configuration from config.rs, and each SDK's API from its source and doc
// comments (sdk.mjs). Written under src/content/docs/docs and not committed
// (.gitignore).

import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SDKS, members } from './sdk.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const core = join(root, 'server/crates/agentim-core');
const out = join(here, '..', 'src/content/docs/docs');

const write = (rel, text) => {
  const f = join(out, rel);
  mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, text);
};
const fm = (title, description, order) => `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n${order === undefined ? '' : `sidebar:\n  order: ${order}\n`}---\n\n<!-- Generated by site/scripts/reference.mjs: edit the source, not this file. -->\n\n`;
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// ------------------------------------------------------------- open API

export function openApi() {
  const doc = JSON.parse(readFileSync(join(core, 'openapi.json'), 'utf8'));
  const schemas = doc.components?.schemas ?? {};
  const ref = (s) => (s?.$ref ? s.$ref.split('/').pop() : null);
  const type = (s) => {
    if (!s) return '';
    if (ref(s)) return `[${ref(s)}](/docs/reference/open-api/schemas/#${slug(ref(s))})`;
    if (s.type === 'array') return `${type(s.items)}[]`;
    if (s.enum) return s.enum.map((e) => `\`${e}\``).join(' \\| ');
    return s.type ?? 'any';
  };
  const props = (s, depth = 0) => {
    const obj = ref(s) ? schemas[ref(s)] : s;
    if (!obj?.properties) return '';
    const req = new Set(obj.required ?? []);
    let t = depth ? '' : '| Field | Type | Required | Description |\n|---|---|---|---|\n';
    for (const [k, v] of Object.entries(obj.properties)) t += `| \`${k}\` | ${type(v)} | ${req.has(k) ? 'yes' : ''} | ${esc(v.description)} |\n`;
    return t;
  };
  const groups = new Map();
  for (const [path, ops] of Object.entries(doc.paths)) {
    const g = path.split('/')[2]?.split(/[:{]/)[0] || 'other';
    for (const [method, op] of Object.entries(ops)) {
      if (!groups.has(g)) groups.set(g, []);
      groups.get(g).push({ path, method: method.toUpperCase(), op });
    }
  }
  const ops = [];
  let order = 2;
  for (const [g, list] of [...groups].sort()) {
    const title = g[0].toUpperCase() + g.slice(1);
    let t = fm(title, `Open API: ${title.toLowerCase()} endpoints.`, order++);
    for (const { path, method, op } of list) {
      ops.push(`${method} ${path}`);
      t += `## \`${method} ${path}\`\n\n${op.summary ?? ''}${op.description ? `\n\n${op.description}` : ''}\n\n`;
      t += `- **Scope**: ${op['x-scope'] ? `\`${op['x-scope']}\`` : 'none'}\n`;
      if (op['x-idempotent'] || method === 'POST') t += '- **Idempotency**: send `Idempotency-Key`; a retry with the same key returns the first result.\n';
      t += '\n';
      const params = op.parameters ?? [];
      if (params.length) {
        t += '| Parameter | In | Type | Required | Description |\n|---|---|---|---|---|\n';
        for (const p of params) t += `| \`${p.name}\` | ${p.in} | ${type(p.schema)} | ${p.required ? 'yes' : ''} | ${esc(p.description)} |\n`;
        t += '\n';
      }
      const body = op.requestBody?.content?.['application/json']?.schema ?? op.requestBody?.content?.['application/octet-stream']?.schema;
      if (body) t += `**Request body**${op.requestBody.content['application/octet-stream'] ? ' (the file\'s bytes)' : ''}\n\n${props(body) || type(body)}\n\n`;
      for (const [code, r] of Object.entries(op.responses ?? {})) {
        if (code === 'default') continue;
        const s = r.content?.['application/json']?.schema;
        t += `**${code}** ${esc(r.description)}\n\n${s ? props(s) || type(s) : ''}\n\n`;
      }
      t += 'Errors are [problem documents](/docs/reference/errors/) with a `code`.\n\n';
    }
    write(`reference/open-api/${slug(g)}.md`, t);
  }
  let t = fm('Open API', 'The HTTPS API for your backend: authentication, scopes, acting as a user or the system, idempotency, errors, rate limits and every endpoint.', 1);
  t += `The open API is for your backend, never for apps. Base path \`/v1\`; the OpenAPI 3.1 document is at \`GET /v1/openapi.json\`. The [server SDKs](/docs/server-sdks/) wrap every endpoint.\n\n`;
  t += '## Authentication\n\nSend an API key: `Authorization: Bearer ak_…`. Create keys with `agentim api-key create --name backend --scopes …`, in the console or the admin API. Keys can expire and can be limited to IP ranges; only a hash is stored, and a revoked key stops working within 10 seconds. Plain HTTP is accepted only from the same machine, or behind a TLS proxy with `open_api.behind_proxy = true`.\n\n';
  t += '| Scope | Allows |\n|---|---|\n';
  for (const [k, v] of [
    ['users:read', 'Read profiles, devices and agents'],
    ['users:write', 'Create, import, update, deactivate users; set their permissions'],
    ['conversations:read', 'Read conversations and members'],
    ['conversations:write', 'Create conversations, manage members and roles, dissolve'],
    ['messages:write', 'Send, edit, recall, mark read, upload files, as a user or the system'],
    ['messages:read', 'Read message history and files. Separate because it reveals private conversations; every read is audited'],
    ['agents:read', 'List and export agents'],
    ['agents:write', 'Create agents, issue and revoke keys, stop, resume, transfer, destroy, import'],
    ['tokens:revoke', 'Sign a user out on every device; sign out one device'],
    ['moderation', 'The report queue; silencing members'],
    ['compliance', 'Export and delete user data (GDPR)'],
  ]) t += `| \`${k}\` | ${v} |\n`;
  t += '\n## Acting as someone\n\nCalls that act in a conversation name who acts with `as`: a user id (the call follows exactly that user\'s rules, like their app) or `system` (manage any conversation, send system notices, recall any message; it cannot speak as a user). Every call is audited with the key and the identity.\n\n';
  t += '## Conventions\n\n| | |\n|---|---|\n';
  t += '| Idempotency | Every `POST` takes `Idempotency-Key` (1–255 characters), kept for 24 hours. The same key and body returns the first result with `Idempotent-Replayed: true`; a different body is `422`; while the first is running, `409`. Messages also deduplicate by `clientMsgId` |\n';
  t += '| Errors | `application/problem+json` with a stable `code`, the same codes as the WebSocket protocol ([error codes](/docs/reference/errors/)) |\n';
  t += '| Batches | One result per item, `{"results": [{"ok": true, …}, {"ok": false, "code": "blocked"}]}`; one failure does not stop the others |\n';
  t += '| Rate limits | A token bucket per key, 100 per second with bursts of 200 by default (`open_api.rate_per_second`, `open_api.burst`). `RateLimit-Policy` and `RateLimit` headers; over the limit `429` with `Retry-After` |\n';
  t += '| Times and ids | Times are milliseconds since 1970; ids are strings. User ids are yours: 1–64 of letters, digits and `_-.@:` |\n';
  t += '| Versioning | `/v1` only grows: new optional fields and endpoints, never removals |\n\n';
  t += '## Endpoints\n\n| Endpoint | Summary |\n|---|---|\n';
  for (const [path, opsOf] of Object.entries(doc.paths)) {
    const g = path.split('/')[2]?.split(/[:{]/)[0] || 'other';
    for (const [method, op] of Object.entries(opsOf)) {
      const anchor = `${method} ${path}`.toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
      t += `| [\`${method.toUpperCase()} ${path}\`](/docs/reference/open-api/${slug(g)}/#${anchor}) | ${esc(op.summary)} |\n`;
    }
  }
  write('reference/open-api/index.md', t);
  t = fm('Schemas', 'Open API: the shared objects.', 99);
  for (const [name, s] of Object.entries(schemas)) t += `## ${name}\n\n${esc(s.description)}\n\n${props({ $ref: `#/components/schemas/${name}` })}\n\n`;
  write('reference/open-api/schemas.md', t);
  return ops;
}

// ------------------------------------------------------------- Rust sources

/** Doc comments, attributes and items of a Rust block, line by line. */
function docBefore(lines, i) {
  const doc = [];
  let j = i - 1;
  while (j >= 0 && /^\s*#\[/.test(lines[j])) j--;
  while (j >= 0 && /^\s*\/\/\//.test(lines[j])) doc.unshift(lines[j--].replace(/^\s*\/\/\/ ?/, ''));
  return doc.join(' ').trim();
}

function rustType(t) {
  t = t.trim().replace(/crate::[a-z_]+::/g, '');
  const opt = /^Option<(.*)>$/.exec(t);
  const base = (opt ? opt[1] : t).replace(/^Vec<(.*)>$/, '$1[]').replace(/\bString\b/, 'string').replace(/\bi64\b|\bu64\b|\bu32\b|\busize\b|\bf64\b/, 'number').replace(/\bbool\b/, 'boolean').replace(/\bValue\b/, 'JSON');
  return { type: base, optional: !!opt };
}

/** The `ClientMsg` variants: op name, doc, fields. */
export function clientOps() {
  const src = readFileSync(join(core, 'src/model.rs'), 'utf8');
  const a = src.indexOf('pub enum ClientMsg {');
  const b = src.indexOf('\n}\n', a);
  const lines = src.slice(a, b).split('\n');
  const ops = [];
  for (let i = 1; i < lines.length; i++) {
    const m = /^ {4}([A-Z][A-Za-z]*)(?: \{(.*)\},?| \{|,)$/.exec(lines[i]);
    if (!m) continue;
    const name = m[1].replace(/[A-Z]/g, (c, k) => (k ? '_' : '') + c.toLowerCase());
    const op = { name, doc: docBefore(lines, i), fields: [] };
    const field = (line, doc, attrs) => {
      const f = /^\s*([a-z_]+): (.+?),?$/.exec(line);
      if (!f) return;
      const { type, optional } = rustType(f[2]);
      op.fields.push({ name: f[1], type, optional: optional || /serde\(default/.test(attrs), doc });
    };
    if (m[2] !== undefined) {
      for (const part of m[2].split(/,\s*/)) field(part, '', '');
    } else if (lines[i].endsWith('{')) {
      let attrs = '';
      for (i++; i < lines.length && !/^ {4}\},?$/.test(lines[i]); i++) {
        if (/^\s*#\[/.test(lines[i])) attrs += lines[i];
        else if (/^\s*[a-z_]+:/.test(lines[i])) {
          field(lines[i], docBefore(lines, i), attrs);
          attrs = '';
        }
      }
    }
    ops.push(op);
  }
  return ops;
}

/** Structs of config.rs: fields with doc, type and default. */
export function configSections() {
  const src = readFileSync(join(core, 'src/config.rs'), 'utf8');
  const lines = src.split('\n');
  const structs = {};
  for (let i = 0; i < lines.length; i++) {
    const m = /^pub struct (\w+) \{/.exec(lines[i]);
    if (!m) continue;
    const s = { doc: docBefore(lines, i), fields: [] };
    let attrs = '';
    for (i++; !/^\}/.test(lines[i]); i++) {
      if (/^\s*#\[/.test(lines[i])) attrs += lines[i];
      const f = /^ {4}pub ([a-z_]+): (.+),$/.exec(lines[i]);
      if (f) {
        // Set by the server itself, not in the file.
        if (!/serde\(skip\)/.test(attrs)) s.fields.push({ name: f[1], type: f[2], doc: docBefore(lines, i), rename: /rename = "([^"]+)"/.exec(attrs)?.[1] });
        attrs = '';
      }
    }
    structs[m[1]] = s;
  }
  const defaults = {};
  const re = /^impl Default for (\w+) \{/;
  for (let i = 0; i < lines.length; i++) {
    const m = re.exec(lines[i]);
    if (!m) continue;
    const d = {};
    for (i++; !/^\}/.test(lines[i]); i++) {
      const f = /^ {12}([a-z_]+): (.+),$/.exec(lines[i]);
      if (f) d[f[1]] = f[2].replace(/\.into\(\)|\.to_string\(\)|String::from\((.*)\)/g, '$1').trim();
    }
    defaults[m[1]] = d;
  }
  const toml = (d) => {
    if (d === undefined) return undefined;
    // `[sync]` takes its defaults from the hub's SyncConfig.
    const fromSync = /^d\.(\w+)(?:\.(\d))?$/.exec(d);
    if (fromSync) {
      const v = defaults.SyncConfig?.[fromSync[1]];
      const tuple = v && /^\((.*), (.*)\)$/.exec(v);
      return toml(tuple ? tuple[Number(fromSync[2]) + 1] : v);
    }
    if (/^(None|vec!\[\]|Vec::new\(\)|Default::default\(\)|\w+::default\(\))$/.test(d)) return undefined;
    const e = /^\w+::(\w+)$/.exec(d);
    if (e) return `"${e[1].replace(/[A-Z]/g, (c, k) => (k ? '_' : '') + c.toLowerCase())}"`;
    const some = /^Some\((.*)\)$/.exec(d);
    if (some) return toml(some[1]);
    const shift = /^(\d+) << (\d+)$/.exec(d);
    if (shift) return String(Number(shift[1]) * 2 ** Number(shift[2]));
    return d.replace(/_(?=\d)/g, '');
  };
  const sections = [];
  const walk = (struct, path, array) => {
    const s = structs[struct];
    if (!s) return;
    const own = [];
    const nested = [];
    for (const f of s.fields) {
      const inner = f.type.replace(/^(Option|Vec)<(.*)>$/, '$2');
      const key = f.rename ?? f.name;
      if (structs[inner] && structs[inner].fields.length) nested.push([inner, path ? `${path}.${key}` : key, f.type.startsWith('Vec<')]);
      else own.push({ ...f, name: key, default: toml(defaults[struct]?.[f.name]) });
    }
    // A section before the ones inside it.
    if (path && own.length) sections.push({ path, array, doc: s.doc, fields: own });
    for (const n of nested) walk(...n);
  };
  walk('Config', '', false);
  return sections;
}

